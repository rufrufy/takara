import assert from 'node:assert/strict';
import {loadSource} from './test-source-loader.mjs';
const {parseFinancialBackup,createFinancialBackup,backupSummary}=await loadSource('src/lib/jsonBackup.ts');
const at='2026-11-17T03:00:00Z';
const household={id:'hh',name:'Test household'};
const wallet={id:'wallet',householdId:'hh',name:'Cash',type:'cash',currency:'IDR',balance:800,isArchived:false,createdAt:at,updatedAt:at};
const tx={id:'tx',householdId:'hh',type:'income',amount:800,destinationWalletId:'wallet',addedBy:'Test',effectiveAt:at,createdAt:at,updatedAt:at,status:'POSTED',categoryType:null};
const legacy={activeHouseholdId:'hh',households:[household],wallets:[wallet],categories:[],transactions:[tx],debts:[],labels:['Test'],currentUser:{pinHash:'must-not-export'},aiConfig:{apiKey:'must-not-export'},supabaseConfig:{secretKey:'must-not-export'},sessions:[{token:'must-not-export'}]};
const backup=createFinancialBackup(legacy);
assert.equal(backup.wallets[0].balance,800);
assert.equal(JSON.stringify(backup).includes('must-not-export'),false);
const parsed=parseFinancialBackup(JSON.stringify(backup),'hh');
assert.equal(parsed.transactions[0].amount,800);
assert.equal(parsed.wallets[0].balance,0,'Server rebuilds ledger balances rather than trusting wallet snapshots');
assert.equal(parseFinancialBackup(JSON.stringify(legacy),'hh').transactions.length,1);
assert.equal(backupSummary(parsed).totalIncome,800);
assert.throws(()=>parseFinancialBackup('{broken','hh'),/JSON/);
assert.throws(()=>parseFinancialBackup(JSON.stringify(backup),'other'),/household/);
assert.throws(()=>parseFinancialBackup(JSON.stringify({...backup,transactions:[{...tx,amount:1.5}]}),'hh'),/rupiah/);
assert.throws(()=>parseFinancialBackup(JSON.stringify({...backup,transactions:[tx,tx]}),'hh'),/duplikat/);
assert.throws(()=>parseFinancialBackup(JSON.stringify({...backup,transactions:[{...tx,destinationWalletId:'missing'}]}),'hh'),/Referensi/);
assert.throws(()=>parseFinancialBackup(JSON.stringify({...backup,transactions:[{...tx,imageUrl:'supabase-storage://receipts/foreign/a.jpg'}]}),'hh'),/Lampiran/);
assert.throws(()=>parseFinancialBackup(JSON.stringify({...backup,version:99}),'hh'),/Versi/);
console.log('PASS: JSON export/import roundtrip, legacy compatibility, credentials excluded, balances rebuilt, cross-household/version/reference/duplicate/amount/receipt validation');
